METRIC_COLS = ["direction", "ic_mean", "icir", "ls_annual", "ls_sharpe",
               "calmar", "long_excess_annual", "monotonicity"]


def main() -> None:
    ckpt = OUTPUT_DIR / "checkpoint.json"
    data = json.loads(ckpt.read_text(encoding="utf-8"))
    factors = data["stored_factors"]

    # 与 export 的 manifest.csv 对齐（拿 file 列；无则重建 file 名）
    file_by_hash: dict[str, str] = {}
    manifest = OUTPUT_DIR / "factors" / "manifest.csv"
    if manifest.exists():
        with open(manifest, encoding="utf-8-sig") as f:
            for row in csv.DictReader(f):
                h = (row.get("hash") or "").strip()
                if h:
                    file_by_hash[h] = row.get("file", "")

    rows = []
    for i, fac in enumerate(factors, 1):
        h = fac["hash"]
        m = fac.get("metrics", {})
        label, explain = CLASSIFY.get(h, ("待分类", "—"))
        rows.append({
            "idx": i,
            "file": file_by_hash.get(h, ""),
            "expr": fac.get("expr", ""),
            "hash": h,
            **{c: m.get(c) for c in METRIC_COLS},
            "label": label,
            "return_source": explain,
        })

    out = OUTPUT_DIR / "factors" / "manifest_classified.csv"
    with open(out, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    # 覆盖统计
    from collections import Counter
    cnt = Counter(r["label"] for r in rows)
    unclassified = [r["hash"][:8] for r in rows if r["label"] == "待分类"]
    print(f"写入 {out}({len(rows)} 因子)")
    print("\n标签覆盖(21 类):")
    for lb in LABELS:
        n = cnt.get(lb, 0)
        flag = "" if n else "  ← 空"
        print(f"  {n:2d}  {lb}{flag}")
    if unclassified:
        print(f"\n待分类 hash: {unclassified}")


if __name__ == "__main__":
    main()
